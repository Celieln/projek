<?php

error_reporting(E_ALL);
ini_set('display_errors', 1);

require 'functions.php';

/*
|--------------------------------------------------------------------------
| VALIDASI INPUT
|--------------------------------------------------------------------------
*/

if(!isset($_POST['name'])){

    exit('Folder name required');

}

/*
|--------------------------------------------------------------------------
| GET NAME
|--------------------------------------------------------------------------
*/

$name =
trim(
    $_POST['name']
);

if($name == ''){

    exit('Folder name empty');

}

/*
|--------------------------------------------------------------------------
| NORMALIZE PATH
|--------------------------------------------------------------------------
*/

$name =
str_replace(
    '\\',
    '/',
    $name
);

$name =
trim(
    $name,
    '/'
);

/*
|--------------------------------------------------------------------------
| CLEAN PATH
|--------------------------------------------------------------------------
*/

$name =
cleanPath(
    $name
);

/*
|--------------------------------------------------------------------------
| VALIDASI KARAKTER
|--------------------------------------------------------------------------
*/

if(

    preg_match(
        '/(\.\.)/',
        $name
    )

){

    exit('Invalid folder path');

}

/*
|--------------------------------------------------------------------------
| FINAL PATH
|--------------------------------------------------------------------------
*/

$path =
$ROOT_PATH
. '/'
. $name;

/*
|--------------------------------------------------------------------------
| REALPATH SECURITY
|--------------------------------------------------------------------------
*/

$parentPath =
dirname($path);

if(!file_exists($parentPath)){

    /*
    |--------------------------------------------------------------------------
    | CREATE PARENT DIRECTORY
    |--------------------------------------------------------------------------
    */

    if(

        !mkdir(
            $parentPath,
            0777,
            true
        )

    ){

        exit('Failed create parent folder');

    }

}

/*
|--------------------------------------------------------------------------
| CHECK EXISTS
|--------------------------------------------------------------------------
*/

if(file_exists($path)){

    exit('Folder already exists');

}

/*
|--------------------------------------------------------------------------
| CREATE FOLDER RECURSIVE
|--------------------------------------------------------------------------
*/

if(

    !mkdir(
        $path,
        0777,
        true
    )

){

    exit('Failed create folder');

}

/*
|--------------------------------------------------------------------------
| RELATIVE PATH
|--------------------------------------------------------------------------
*/

$relativePath =
str_replace(
    '\\',
    '/',
    $name
);

/*
|--------------------------------------------------------------------------
| ABSOLUTE PATH
|--------------------------------------------------------------------------
*/

$absolutePath =
str_replace(
    '\\',
    '/',
    realpath($path)
);

/*
|--------------------------------------------------------------------------
| INSERT DATABASE
|--------------------------------------------------------------------------
*/

$stmt =
$pdo->prepare(

    "INSERT INTO folders
    (
        folder_name,
        folder_path
    )

    VALUES (?, ?)"

);

$stmt->execute([

    basename(
        $relativePath
    ),

    $relativePath

]);

/*
|--------------------------------------------------------------------------
| AUDIT LOG
|--------------------------------------------------------------------------
*/

audit(

    'CREATE_FOLDER',

    $absolutePath

);

/*
|--------------------------------------------------------------------------
| RESPONSE
|--------------------------------------------------------------------------
*/

echo 'Folder created successfully';