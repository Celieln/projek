<?php

error_reporting(E_ALL);
ini_set('display_errors', 1);

require 'config.php';

/*
|--------------------------------------------------------------------------
| TOTAL SIZE
|--------------------------------------------------------------------------
*/

$totalSize = 0;

/*
|--------------------------------------------------------------------------
| CHECK ROOT PATH
|--------------------------------------------------------------------------
*/

if(!file_exists($ROOT_PATH)){

    exit('0 MB');

}

/*
|--------------------------------------------------------------------------
| SCAN DIRECTORY
|--------------------------------------------------------------------------
*/

$iterator =
new RecursiveIteratorIterator(

    new RecursiveDirectoryIterator(

        $ROOT_PATH,

        RecursiveDirectoryIterator::SKIP_DOTS

    )

);

/*
|--------------------------------------------------------------------------
| CALCULATE FILE SIZE
|--------------------------------------------------------------------------
*/

foreach($iterator as $file){

    if($file->isFile()){

        $totalSize +=
        $file->getSize();

    }

}

/*
|--------------------------------------------------------------------------
| FORMAT SIZE
|--------------------------------------------------------------------------
*/

function formatSize($bytes)
{

    if($bytes >= 1073741824){

        return round(

            $bytes / 1073741824,

            2

        ) . ' GB';

    }

    if($bytes >= 1048576){

        return round(

            $bytes / 1048576,

            2

        ) . ' MB';

    }

    if($bytes >= 1024){

        return round(

            $bytes / 1024,

            2

        ) . ' KB';

    }

    return $bytes . ' B';

}

/*
|--------------------------------------------------------------------------
| OUTPUT
|--------------------------------------------------------------------------
*/

echo formatSize($totalSize);