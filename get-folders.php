<?php

error_reporting(E_ALL);
ini_set('display_errors', 1);

require 'config.php';

/*
|--------------------------------------------------------------------------
| RESULT
|--------------------------------------------------------------------------
*/

$folders = [];

/*
|--------------------------------------------------------------------------
| CHECK ROOT PATH
|--------------------------------------------------------------------------
*/

if(!file_exists($ROOT_PATH)){

    header(
        'Content-Type: application/json'
    );

    echo json_encode([]);

    exit;

}

/*
|--------------------------------------------------------------------------
| SCAN RECURSIVE DIRECTORY
|--------------------------------------------------------------------------
*/

$iterator =
new RecursiveIteratorIterator(

    new RecursiveDirectoryIterator(

        $ROOT_PATH,

        RecursiveDirectoryIterator::SKIP_DOTS

    ),

    RecursiveIteratorIterator::SELF_FIRST

);

/*
|--------------------------------------------------------------------------
| GET ALL FOLDERS
|--------------------------------------------------------------------------
*/

foreach($iterator as $file){

    /*
    |--------------------------------------------------------------------------
    | ONLY DIRECTORY
    |--------------------------------------------------------------------------
    */

    if($file->isDir()){

        /*
        |--------------------------------------------------------------------------
        | FULL PATH
        |--------------------------------------------------------------------------
        */

        $fullPath =
        $file->getPathname();

        /*
        |--------------------------------------------------------------------------
        | RELATIVE PATH
        |--------------------------------------------------------------------------
        */

        $relativePath =
        str_replace(

            '\\',

            '/',

            str_replace(

                realpath($ROOT_PATH),

                '',

                realpath($fullPath)

            )

        );

        /*
        |--------------------------------------------------------------------------
        | REMOVE FIRST SLASH
        |--------------------------------------------------------------------------
        */

        $relativePath =
        ltrim(
            $relativePath,
            '/'
        );

        /*
        |--------------------------------------------------------------------------
        | EMPTY ROOT SKIP
        |--------------------------------------------------------------------------
        */

        if($relativePath == ''){

            continue;

        }

        /*
        |--------------------------------------------------------------------------
        | DEPTH
        |--------------------------------------------------------------------------
        */

        $depth =
        substr_count(
            $relativePath,
            '/'
        );

        /*
        |--------------------------------------------------------------------------
        | FOLDER NAME
        |--------------------------------------------------------------------------
        */

        $folderName =
        basename(
            $relativePath
        );

        /*
        |--------------------------------------------------------------------------
        | PUSH ARRAY
        |--------------------------------------------------------------------------
        */

        $folders[] = [

            'folder_name' =>
            $folderName,

            'folder_path' =>
            $relativePath,

            'full_path' =>
            str_replace(
                '\\',
                '/',
                $fullPath
            ),

            'depth' =>
            $depth

        ];

    }

}

/*
|--------------------------------------------------------------------------
| SORT BY PATH
|--------------------------------------------------------------------------
*/

usort(

    $folders,

    function($a, $b){

        return strcmp(

            $a['folder_path'],

            $b['folder_path']

        );

    }

);

/*
|--------------------------------------------------------------------------
| JSON
|--------------------------------------------------------------------------
*/

header(
    'Content-Type: application/json'
);

echo json_encode(

    $folders,

    JSON_PRETTY_PRINT

);